"""Что занимает вещь на человеке — две вещи в одно место надеть нельзя. Для магазинов без ИИ-стилиста
(в «Силе в Стиле» то же правило живёт в svs_stylist.py). Учитывает и женские вещи: платья, юбки, комбинезоны."""
import re

SLOTS = [
    (r"^(КОСТЮМ|КОМПЛЕКТ|ТРОЙК|ДВОЙК|ПЛАТЬ|САРАФАН|КОМБИНЕЗОН)", {"top", "bottom"}, "комплект/платье"),
    (r"^(БРЮК|ДЖИНС|ШОРТ|ЧИНОС|КАРГО|ЮБК|ЛОСИН|ЛЕГГИН|КЮЛОТ|ПАЛАЦЦО)", {"bottom"}, "низ"),
    (r"^(ЖИЛЕТ|ПИДЖАК|ЖАКЕТ|БЛЕЙЗЕР|КУРТК|БОМБЕР|ВЕТРОВК|ПАРК|ПУХОВИК|ПАЛЬТО|ПЛАЩ|ДУБЛ[ЁЕ]НК|ШУБ|ОВЕРШОТ|ТРЕНЧ|АНОРАК)",
     {"outer"}, "верхняя одежда"),
    (r"^(КРОССОВ|КЕД|ТУФЛ|ЛОФЕР|МОКАСИН|БОТИН|САПОГ|БОТФОРТ|СЛИП|ДЕРБИ|ОКСФОРД|ЧЕЛСИ|САНДАЛ|БОСОНОЖ|БАЛЕТК|"
     r"МЮЛИ|ШЛ[ЁЕ]П|ОБУВ)", {"shoes"}, "обувь"),
]


def slots(title):
    t = (title or "").strip().upper()
    for rx, sl, name in SLOTS:
        if re.match(rx, t):
            return sl, name
    return set(), ""


def conflict(titles):
    seen = {}
    for t in titles:
        sl, name = slots(t)
        for s_ in sl:
            if s_ in seen:
                a = seen[s_]
                if "комплект/платье" in (slots(a)[1], name):
                    return f"{a} и {t} не надеть вместе — выберите что-то одно."
                return f"{a} и {t} — две вещи одного типа ({name}). Для образа выберите одну."
            seen[s_] = t
    return None
